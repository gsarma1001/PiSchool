function gradeMappings(firstGrade: number, lastGrade: number, sourceId: string) {
  return usGradeFilterOptions
    .filter((grade) => {
      const number = Number(grade.id.replace("grade-", ""));
      return Number.isInteger(number) && number >= firstGrade && number <= lastGrade;
    })
    .map((grade) => ({
      label: grade.label.replace(" (US)", ""),
      equivalent: grade.label,
      usGradeId: grade.id,
      sourceId,
    }));
}

