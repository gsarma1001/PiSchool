export const eventRecords: EventRecord[] = eventEditions.map((edition) => {
  const family = eventFamilies.find((item) => item.id === edition.familyId);
  if (!family) throw new Error(`Unknown event family for ${edition.id}.`);
  return {
    ...edition,
    name: edition.displayName ?? family.name,
    organizer: family.organizer,
    category: family.category,
    officialUrl: family.officialUrl,
    description: edition.description ?? family.description,
    familyName: family.name,
    familyAliases: family.aliases,
    purpose: family.purpose,
  };
});

validateEventRecords(eventRecords);
validateEventFamilies(eventFamilies, eventRecords);

export function getPublishedEvents(includeArchived = false): EventRecord[] {
  return eventRecords.filter(
    (event) =>
      event.editorialStatus === "published" ||
      (includeArchived && event.editorialStatus === "archived"),
  );
}

export function getPublishedEventSummaries(includeArchived = false): EventSummary[] {
  return getPublishedEvents(includeArchived).map(({ sources: _sources, resources: _resources, ...summary }) => summary);
}

export function getPublicEventBySlug(slug: string): EventRecord | undefined {
  return getPublishedEvents(true).find((event) => event.slug === slug);
}
